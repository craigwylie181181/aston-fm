/* Builds per-page metadata with a self-referencing canonical URL and matching social tags */
export function pageMetadata({
  title,
  description,
  path,
  type = 'website',
  publishedTime,
}: {
  title: string | { absolute: string };
  description: string;
  path: string;
  type?: 'website' | 'article';
  publishedTime?: string;
}): Metadata {
  const socialTitle = typeof title === 'string' ? `${title} | Aston FM` : title.absolute;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type,
      locale: 'en_GB',
      siteName: SITE_NAME,
      url: path,
      title: socialTitle,
      description,
      ...(publishedTime ? { publishedTime } : {}),
      images: [OG_IMAGE],
    },
    twitter: {
      card: 'summary_large_image',
      title: socialTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}

export function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}
